/**
 * GemBench equipment definitions for the fab in a box. One YAML per tool, written from a template.
 * The shape follows GemBench's own examples/equipment/etcher.yaml. Every tool gets the same processing
 * state model, a FINISH command so the host decides how long a step takes, and the `fabTwin` section
 * that tells GemBench's bridge which FabTwin tool the equipment is.
 */
export type ToolKind = "litho" | "etch" | "dep" | "cmp" | "metro";

export interface GemTool {
  id: string;
  kind: ToolKind;
  hsmsPort: number;
  wsPort: number;
}

/** Status variable ids the host reads. Metrology exposes one measurement per parameter. */
export const SVID = { CD: 20, OVL: 21, THK: 22 } as const;

const SENSORS: Record<ToolKind, string> = {
  litho: `  - { id: 10, name: StageTemperature, units: C, format: F4, generator: { kind: sine, center: 22, amplitude: 0.05, periodSeconds: 40 } }
  - { id: 11, name: ExposureDose, units: mJ/cm2, format: F4, generator: { kind: randomWalk, center: 28, step: 0.04, seed: 3 } }`,
  etch: `  - { id: 10, name: ChamberTemperature, units: C, format: F4, generator: { kind: sine, center: 60, amplitude: 2, periodSeconds: 25 } }
  - { id: 11, name: ChamberPressure, units: mTorr, format: F4, generator: { kind: randomWalk, center: 12, step: 0.05, seed: 7 } }`,
  dep: `  - { id: 10, name: SusceptorTemperature, units: C, format: F4, generator: { kind: sine, center: 400, amplitude: 3, periodSeconds: 30 } }
  - { id: 11, name: ChamberPressure, units: Torr, format: F4, generator: { kind: randomWalk, center: 2.5, step: 0.02, seed: 5 } }`,
  cmp: `  - { id: 10, name: PlatenSpeed, units: rpm, format: F4, generator: { kind: sine, center: 60, amplitude: 1, periodSeconds: 20 } }
  - { id: 11, name: DownForce, units: psi, format: F4, generator: { kind: randomWalk, center: 3.2, step: 0.02, seed: 9 } }`,
  metro: `  - { id: 20, name: CdValue, units: nm, format: F4, generator: { kind: randomWalk, center: 45, step: 0.25, seed: SEED } }
  - { id: 21, name: OverlayValue, units: nm, format: F4, generator: { kind: randomWalk, center: 3.2, step: 0.15, seed: SEED } }
  - { id: 22, name: ThicknessValue, units: nm, format: F4, generator: { kind: randomWalk, center: 120, step: 0.5, seed: SEED } }`,
};

export function equipmentYaml(t: GemTool, seed: number): string {
  const name = `GB-${t.id}`;
  return `# Generated by scripts/fab-in-a-box.ts. Edit the template in scripts/lib/gem-equipment.ts, not this file.
equipment:
  name: ${name}
  model: GBFAB-${t.kind.toUpperCase()}
  revision: 0.1.0
  deviceId: 0
  listen: 127.0.0.1:${t.hsmsPort}
  timers: { t3: 10000, t5: 10000, t6: 5000, t7: 5000, t8: 5000 }
  control: { initial: hostOffline, onlineMode: remote }
  communication: { initiate: false }
  controlStateEvents: { equipmentOffline: 1, hostOffline: 2, onlineLocal: 3, onlineRemote: 4 }

statusVariables:
  - { id: 1, name: ControlState, source: controlState }
  - { id: 2, name: ProcessState, source: processState }
  - { id: 3, name: CommState, source: commState }
  - { id: 4, name: Clock, source: clock }
  - { id: 5, name: ControlStateName, source: controlStateName }
  - { id: 6, name: ProcessStateName, source: processStateName }
${SENSORS[t.kind].replace(/SEED/g, String(seed))}
  - { id: 30, name: LotId, format: A, value: "" }
  - { id: 31, name: RecipeName, format: A, value: "" }

dataVariables:
  - { id: 50, name: WafersPerLot, format: U2, value: 25 }

events:
  - { id: 1, name: ControlStateEquipmentOffline }
  - { id: 2, name: ControlStateHostOffline }
  - { id: 3, name: ControlStateOnlineLocal }
  - { id: 4, name: ControlStateOnlineRemote }
  - { id: 101, name: ProcessStarted }
  - { id: 102, name: ProcessCompleted }
  - { id: 103, name: ProcessPaused }

alarms:
  - { id: 1001, name: ChamberFault, text: "Chamber fault on ${t.id}", category: equipmentSafety }
  - { id: 1002, name: LowGasFlow, text: "Process gas flow below limit on ${t.id}", category: parameterControlWarning }

processing:
  initial: Idle
  states: [Idle, Setup, Ready, Executing, Paused, Complete]
  transitions:
    - { from: Idle, trigger: SETUP, to: Setup }
    - { from: Setup, trigger: READY, to: Ready }
    - { from: Idle, trigger: START, to: Executing }
    - { from: Ready, trigger: START, to: Executing }
    - { from: Executing, trigger: PAUSE, to: Paused }
    - { from: Paused, trigger: RESUME, to: Executing }
    - { from: Executing, trigger: COMPLETE, to: Complete }
    - { from: Executing, trigger: ABORT, to: Idle }
    - { from: Paused, trigger: ABORT, to: Idle }
    - { from: Complete, trigger: RESET, to: Idle }
  stateEvents: { Executing: 101, Complete: 102, Paused: 103 }

remoteCommands:
  - name: START
    description: Start a lot. The host ends the step with FINISH.
    allowedStates: [Idle, Ready]
    parameters:
      - { name: LotID, format: A, required: true }
      - { name: RecipeName, format: A }
    effects:
      - { set: LotId, from: LotID }
      - { set: RecipeName, from: RecipeName }
      - { trigger: START }
  - name: FINISH
    description: End the running step and return the tool to idle.
    allowedStates: [Executing]
    effects:
      - { trigger: COMPLETE }
      - { after: 1s, trigger: RESET }
  - { name: ABORT, allowedStates: [Executing, Paused], effects: [{ trigger: ABORT }] }

fabTwin:
  toolId: ${t.id}
  executingState: Executing
  lotIdVariable: LotId
  recipeVariable: RecipeName
  stateMap:
    Idle: STANDBY
    Setup: ENGINEERING
    Ready: STANDBY
    Executing: PRODUCTIVE
    Paused: STANDBY
    Complete: STANDBY
`;
}
