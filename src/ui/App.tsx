import dynamic from "next/dynamic";
import { useCallback, useEffect, useMemo, useState } from "react";
import { useFab } from "@/store/useFab";
import { ToolIso } from "@/art/ToolIso";
import { Attention } from "./Attention";
import { Briefing } from "./Briefing";
import { DOCK_TABS, DockBody, DockTabs } from "./Dock";
import type { DockTab } from "./Dock";
import { Floor2D } from "./Floor2D";
import { useMedia } from "./hooks";
import { LiveDialog } from "./LiveDialog";
import { LotPanel } from "./LotPanel";
import { ReportModal } from "./ReportModal";
import { ShiftSummary } from "./ShiftSummary";
import { Btn } from "./kit";
import { Objectives, TopBar } from "./TopBar";
import { ToolPanel } from "./ToolPanel";
import { fmtClock } from "./format";
import type { Speed } from "@/store/useFab";

const FabScene = dynamic(() => import("@/scene/FabScene"), {
  ssr: false,
  loading: () => <div className="flex h-full items-center justify-center text-[12px] text-muted">Loading the 3D floor</div>,
});

function webglAvailable(): boolean {
  try {
    const c = document.createElement("canvas");
    return !!(c.getContext("webgl2") || c.getContext("webgl"));
  } catch {
    return false;
  }
}

function Context() {
  const sel = useFab((s) => s.selection);
  if (sel?.kind === "tool") return <ToolPanel id={sel.id} />;
  if (sel?.kind === "lot") return <LotPanel id={sel.id} />;
  return <ShiftSummary />;
}

function Toasts() {
  const toasts = useFab((s) => s.toasts);
  const dismiss = useFab((s) => s.dismissToast);
  return (
    <div role="status" aria-live="polite" className="pointer-events-none fixed left-1/2 top-16 z-40 flex w-[min(92vw,420px)] -translate-x-1/2 flex-col gap-1.5">
      {toasts.map((t) => (
        <button
          key={t.id}
          type="button"
          onClick={() => dismiss(t.id)}
          className={`enter pointer-events-auto rounded-md border bg-panel px-3 py-2 text-left text-[12px] shadow-[0_8px_24px_rgba(0,0,0,0.5)] ${t.ok ? "border-prd" : "border-sdt"}`}
        >
          {t.text}
        </button>
      ))}
    </div>
  );
}

function Loading() {
  const boot = useFab((s) => s.boot);
  const error = useFab((s) => s.error);
  const init = useFab((s) => s.init);
  return (
    <div className="flex h-dvh flex-col items-center justify-center gap-3 px-6 text-center">
      <ToolIso size={120} kind="etch" lamp={boot === "error" ? "#f0524f" : "#f0b429"} />
      {boot === "error" ? (
        <>
          <p className="text-[15px] font-medium">The simulation could not start</p>
          <p className="max-w-[48ch] text-[12px] text-muted">{error ?? "Unknown error."} FabTwin runs its engine in a Web Worker, so it needs a current browser.</p>
          <Btn variant="primary" onClick={() => init()}>
            Try again
          </Btn>
        </>
      ) : (
        <>
          <p className="text-[15px] font-medium">Booting the fab model</p>
          <p className="text-[12px] text-muted">Building 24 tools, 2 stockers and the hoist loop in a worker.</p>
        </>
      )}
    </div>
  );
}

function Strip({ fps }: { fps: number | null }) {
  const mode = useFab((s) => s.mode);
  const live = useFab((s) => s.live);
  if (mode === "live")
    return (
      <footer className="flex flex-wrap items-center justify-between gap-x-4 border-t border-line bg-panel px-3 py-1 text-[11px] text-muted">
        <span>Live feed from {live.url}. Tool states, alarms and lot events are as received. KPIs are computed here from those events, and vehicle motion is synthesised.</span>
        <span className="flex items-center gap-4">
          <Link href="/integrations" className="inline-flex min-h-6 items-center text-steel underline">
            Integrations
          </Link>
          <span className="num">{fps !== null ? `${fps} fps` : ""}</span>
        </span>
      </footer>
    );
  return (
    <footer className="flex flex-wrap items-center justify-between gap-x-4 border-t border-line bg-panel px-3 py-1 text-[11px] text-muted">
      <span>Portfolio project. Simulated fab: every lot, tool state, alarm and number here is generated by a model, not measured.</span>
      <span className="flex items-center gap-4">
        <Link href="/integrations" className="inline-flex min-h-6 items-center text-steel underline">
          Integrations
        </Link>
        <span className="num">{fps !== null ? `${fps} fps` : ""}</span>
      </span>
    </footer>
  );
}

export function App() {
  const boot = useFab((s) => s.boot);
  const phase = useFab((s) => s.phase);
  const init = useFab((s) => s.init);
  const selection = useFab((s) => s.selection);
  const select = useFab((s) => s.select);
  const viewPref = useFab((s) => s.view);
  const report = useFab((s) => s.report);
  const shiftNo = useFab((s) => s.shiftNo);
  const mobile = useMedia("(max-width: 767px)");
  const gl = useMemo(() => webglAvailable(), []);
  const [briefClosedFor, setBriefClosedFor] = useState(-1);
  const [briefForced, setBriefForced] = useState(false);
  const [reportClosedFor, setReportClosedFor] = useState(-1);
  const [reportForced, setReportForced] = useState(false);
  const [liveOpen, setLiveOpen] = useState(false);
  const [tab, setTab] = useState<DockTab>("equipment");
  const [mtab, setMtab] = useState<"floor" | "alerts" | "lots" | "charts">("floor");
  const [ctab, setCtab] = useState<DockTab>("wip");
  const [fps, setFps] = useState<number | null>(null);
  const showBrief = (phase === "briefing" && briefClosedFor !== shiftNo) || briefForced;
  const showReport = (phase === "ended" && !!report && reportClosedFor !== shiftNo) || reportForced;
  const closeBrief = () => {
    setBriefClosedFor(shiftNo);
    setBriefForced(false);
  };
  const closeReport = () => {
    setReportClosedFor(shiftNo);
    setReportForced(false);
  };
  const view = gl ? viewPref : "2d";

  useEffect(() => {
    init(1);
  }, [init]);

  const onFps = useCallback((n: number) => setFps(n), []);

  if (boot === "idle" || boot === "booting" || boot === "error") return <Loading />;

  const modals = (
    <>
      {showBrief && phase !== "ended" && <Briefing onClose={closeBrief} />}
      {liveOpen && <LiveDialog onClose={() => setLiveOpen(false)} />}
      {showReport && <ReportModal onClose={closeReport} />}
      <Toasts />
    </>
  );

  if (mobile) {
    return (
      <div className="flex h-dvh flex-col">
        <MobileBar onBrief={() => setBriefForced(true)} onReport={() => setReportForced(true)} />
        <main className="min-h-0 flex-1 overflow-y-auto scroll-thin">
          {mtab === "floor" && (
            <div className="flex flex-col">
              <div className="border-b border-line px-3 py-2">
                <Objectives stacked />
              </div>
              <Floor2D portrait />
              <ShiftSummary />
            </div>
          )}
          {mtab === "alerts" && <Attention compact />}
          {mtab === "lots" && <DockBody tab="lots" />}
          {mtab === "charts" && (
            <div className="flex min-h-full flex-col">
              <DockTabs tab={ctab} setTab={setCtab} tabs={DOCK_TABS.filter((t) => t.id !== "lots")} />
              <DockBody tab={ctab} />
            </div>
          )}
        </main>
        {selection && (
          <div className="enter fixed inset-x-0 bottom-[60px] z-30 max-h-[62vh] overflow-y-auto border-t border-accent bg-panel scroll-thin" data-testid="sheet">
            <Context />
            <div className="sticky bottom-0 border-t border-line bg-panel p-2">
              <Btn className="min-h-11 w-full" onClick={() => select(null)}>
                Close details
              </Btn>
            </div>
          </div>
        )}
        <nav aria-label="Sections" className="grid grid-cols-4 border-t border-line bg-panel">
          {(["floor", "alerts", "lots", "charts"] as const).map((k) => (
            <button
              key={k}
              type="button"
              aria-current={mtab === k ? "page" : undefined}
              onClick={() => setMtab(k)}
              className={`min-h-14 text-[13px] ${mtab === k ? "border-t-2 border-accent text-ink" : "border-t-2 border-transparent text-muted"}`}
            >
              {k === "floor" ? "Floor" : k === "alerts" ? "Alerts" : k === "lots" ? "Lots" : "Charts"}
            </button>
          ))}
        </nav>
        <p className="border-t border-line bg-panel px-3 py-1 text-[11px] leading-tight text-muted">Portfolio project. Simulated fab, every number is simulated.</p>
        {modals}
      </div>
    );
  }

  return (
    <div className="flex h-dvh flex-col">
      <TopBar onLive={() => setLiveOpen(true)} onReport={() => setReportForced(true)} onBrief={() => setBriefForced(true)} />
      <div className="border-b border-line bg-panel px-3 py-1 xl:hidden">
        <Objectives />
      </div>
      <div className="flex min-h-0 flex-1">
        <aside className="w-[290px] shrink-0 overflow-y-auto border-r border-line bg-panel scroll-thin" aria-label="Attention queue">
          <Attention />
        </aside>
        <main className="flex min-w-0 flex-1 flex-col">
          <div className="relative min-h-0 flex-1 bg-[#0a0f13]">
            {view === "3d" && gl ? (
              <FabScene onFps={onFps} />
            ) : (
              <div className="flex h-full flex-col overflow-auto">
                {!gl && <p className="border-b border-line bg-panel px-3 py-1 text-[12px] text-sdt">WebGL is not available in this browser, so the 3D floor is off. The 2D map shows the same fab.</p>}
                <div className="min-h-0 flex-1 p-2">
                  <Floor2D />
                </div>
              </div>
            )}
          </div>
          <section className="flex h-[min(300px,38vh)] shrink-0 flex-col border-t border-line bg-panel" aria-label="Instruments">
            <DockTabs tab={tab} setTab={setTab} />
            <DockBody tab={tab} />
          </section>
        </main>
        <aside className="w-[330px] shrink-0 overflow-y-auto border-l border-line bg-panel scroll-thin" aria-label="Selection details">
          <Context />
        </aside>
      </div>
      <Strip fps={view === "3d" && gl ? fps : null} />
      {modals}
    </div>
  );
}

const SPEED_BTN: Array<[Speed, string]> = [[0, "Pause"], [1, "1x"], [10, "10x"], [60, "60x"]];

function MobileBar({ onBrief, onReport }: { onBrief: () => void; onReport: () => void }) {
  const snap = useFab((s) => s.snap);
  const speed = useFab((s) => s.speed);
  const setSpeed = useFab((s) => s.setSpeed);
  const phase = useFab((s) => s.phase);
  return (
    <header className="border-b border-line bg-panel px-3 py-2">
      <div className="flex items-center justify-between gap-2">
        <div>
          <p className="text-[14px] font-semibold leading-tight">FabTwin</p>
          <p className="num text-[13px] leading-tight">{fmtClock(snap?.t ?? 0)} <span className="text-muted">/ {fmtClock(snap?.shiftS ?? 14400)}</span></p>
        </div>
        <div className="text-right">
          <p className="text-[11px] text-muted">Score</p>
          <p className="num text-[16px] leading-tight">{(snap?.score ?? 0).toLocaleString("en-US")}</p>
        </div>
        {phase === "ended" ? <Btn variant="primary" className="min-h-11" onClick={onReport}>Report</Btn> : <Btn className="min-h-11" onClick={onBrief}>Briefing</Btn>}
      </div>
      <div role="group" aria-label="Time controls" className="mt-2 grid grid-cols-4">
        {SPEED_BTN.map(([v, label]) => (
          <button key={v} type="button" aria-pressed={speed === v} disabled={phase === "ended"} onClick={() => setSpeed(v)} className={`num min-h-11 border border-line text-[13px] first:rounded-l-xs last:rounded-r-xs -ml-px first:ml-0 ${speed === v ? "relative z-10 border-accent bg-accent font-medium text-accent-ink" : "bg-raised text-ink"} disabled:text-muted`}>
            {label}
          </button>
        ))}
      </div>
    </header>
  );
}
